#include <string>
#include <vector>

void collect_triples() {
    std::vector<int> values;
    for (int i = 1; i <= 5; ++i) values.push_back(i * 3);
    int total = 0;
    for (std::size_t i = 0; i < values.size(); ++i) total += values[i];
    (void)total;
}

void is_prime() {
    int n = 97;
    bool prime = (n > 1);
    for (int d = 2; d * d <= n; ++d) {
        if (n % d == 0) { prime = false; break; }
    }
    (void)prime;
}

void geometric_sum() {
    int acc = 0;
    int term = 1;
    for (int i = 0; i < 8; ++i) { acc += term; term *= 2; }
    (void)acc;
}

void digit_product() {
    int n = 2345;
    int product = 1;
    while (n > 0) {
        product *= (n % 10);
        n /= 10;
    }
    (void)product;
}

void greatest_divisor() {
    int a = 48, b = 18;
    while (b != 0) {
        int t = a % b;
        a = b;
        b = t;
    }
    (void)a;
}

void swap_values() {
    int a = 5, b = 11;
    int tmp = a;
    a = b;
    b = tmp;
    (void)a;
    (void)b;
}

extern "C" int subtle_hollow();
extern void cedar_signal();
extern void radiant_beacon();

int main() {
    collect_triples();
    is_prime();
    geometric_sum();
    digit_product();
    greatest_divisor();
    swap_values();
    cedar_signal();
    radiant_beacon();
    return subtle_hollow();
}
